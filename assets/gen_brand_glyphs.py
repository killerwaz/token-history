#!/usr/bin/env python3
"""Regenerate scripts/brandfont.py: brand typefaces as outlined SVG glyphs.

Why outlines: the charts are <img>-embedded SVG on a GitHub profile, where a
webfont can never load, so live <text> falls back to whatever the viewer's
machine has. Outlining the glyphs makes Newsreader and Inter render the same
everywhere. The cost is that text in these SVGs is not selectable; every chart
carries role="img" plus an aria-label instead.

Dev-time only. Needs fontTools (`pip install fonttools`); the render pipeline
itself never imports it, so CI and forks stay standard-library only.

    python3 assets/gen_brand_glyphs.py            # downloads the fonts, writes scripts/brandfont.py
    python3 assets/gen_brand_glyphs.py --fonts DIR  # use Newsreader.ttf, Newsreader-Italic.ttf, Inter.ttf already in DIR

Fonts: Newsreader and Inter, both SIL Open Font License 1.1 (notices in
assets/fonts/). Faces generated:

    serif    Newsreader, opsz 72, wght 500   hero numerals, titles
    serif_i  Newsreader Italic, opsz 24, wght 400   decks and captions
    sans     Inter, opsz 14, wght 500        small-caps labels, axis text
"""

import argparse
import os
import sys
import urllib.request

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "scripts", "brandfont.py")
BASE = "https://raw.githubusercontent.com/google/fonts/main/ofl/"
SOURCES = {
    "Newsreader.ttf": "newsreader/Newsreader%5Bopsz,wght%5D.ttf",
    "Newsreader-Italic.ttf": "newsreader/Newsreader-Italic%5Bopsz,wght%5D.ttf",
    "Inter.ttf": "inter/Inter%5Bopsz,wght%5D.ttf",
}

# face -> (file, axis location, prefer the lining-figure glyph variant)
FACES = {
    "serif": ("Newsreader.ttf", {"wght": 500, "opsz": 72}, True),
    "serif_i": ("Newsreader-Italic.ttf", {"wght": 400, "opsz": 24}, True),
    "sans": ("Inter.ttf", {"wght": 500, "opsz": 14}, False),
}

CHARS = [chr(c) for c in range(32, 127)] + list("·–—×→")
UPM = 1000  # every face is normalised to this many units per em

TAIL = '''

def _has(face, ch):
    return ch in FACES[face]["d"]


def measure(face, text, size, tracking=0.0):
    """Advance width of `text` in px at `size`, plus `tracking` px between glyphs."""
    adv = FACES[face]["adv"]
    k = size / float(UPM)
    return sum(adv.get(ch, adv["?"]) * k + tracking for ch in text) - (tracking if text else 0)
'''


def fetch(dest_dir):
    os.makedirs(dest_dir, exist_ok=True)
    for name, rel in SOURCES.items():
        path = os.path.join(dest_dir, name)
        if os.path.exists(path):
            continue
        print("downloading", name)
        urllib.request.urlretrieve(BASE + rel, path)


def build_face(font_path, location, lining):
    font = TTFont(font_path)
    font = instantiateVariableFont(font, location, inplace=False)
    upm = font["head"].unitsPerEm
    k = UPM / float(upm)
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    order = set(font.getGlyphOrder())

    def ntos(v):
        return str(int(round(v)))

    adv, paths = {}, {}
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if name is None:
            continue
        if lining and ch.isdigit() and name + ".lf" in order:
            name += ".lf"
        pen = SVGPathPen(glyphs, ntos=ntos)
        glyphs[name].draw(TransformPen(pen, (k, 0, 0, -k, 0, 0)))
        adv[ch] = int(round(glyphs[name].width * k))
        d = pen.getCommands()
        if d:
            paths[ch] = d
    os2 = font["OS/2"]
    return {"cap": int(round(os2.sCapHeight * k)), "xh": int(round(os2.sxHeight * k)),
            "adv": adv, "d": paths}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts", default=os.path.join(os.path.dirname(HERE), ".fonts-cache"),
                    help="directory holding (or receiving) the three TTFs")
    args = ap.parse_args()
    fetch(args.fonts)

    faces = {}
    for name, (fn, loc, lining) in FACES.items():
        faces[name] = build_face(os.path.join(args.fonts, fn), loc, lining)
        print("{:8s} {} glyphs, cap {} xh {}".format(
            name, len(faces[name]["d"]), faces[name]["cap"], faces[name]["xh"]))

    lines = [
        '"""GENERATED by assets/gen_brand_glyphs.py. Do not edit by hand.',
        "",
        "Outlined glyphs for the brand typefaces (Newsreader, Inter; SIL OFL 1.1),",
        "normalised to UPM units per em with y pointing DOWN and the baseline at 0,",
        "so a glyph drops into an SVG with just translate() and scale(size/UPM).",
        '"""',
        "",
        "UPM = {}".format(UPM),
        "FACES = {",
    ]
    for name, f in faces.items():
        lines.append("    {!r}: {{".format(name))
        lines.append("        'cap': {}, 'xh': {},".format(f["cap"], f["xh"]))
        lines.append("        'adv': {!r},".format(f["adv"]))
        lines.append("        'd': {")
        for ch in sorted(f["d"]):
            lines.append("            {!r}: {!r},".format(ch, f["d"][ch]))
        lines.append("        },")
        lines.append("    },")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + TAIL)
    print("wrote", os.path.relpath(OUT), "({} KB)".format(os.path.getsize(OUT) // 1024))


if __name__ == "__main__":
    sys.exit(main())
